Definition word := list letter.

(** ** 1. The congruence generated by a list of relations *)
Inductive cong (R : list (word * word)) : word -> word -> Prop :=
| c_refl  : forall x, cong R x x
| c_sym   : forall x y, cong R x y -> cong R y x
| c_trans : forall x y z, cong R x y -> cong R y z -> cong R x z
| c_rel   : forall x l r y, In (l, r) R -> cong R (x ++ l ++ y) (x ++ r ++ y).

Lemma cong_app_r : forall R x y z, cong R x y -> cong R (x ++ z) (y ++ z).
Proof.
  intros R x y z H. induction H.
  - apply c_refl.
  - apply c_sym; assumption.
  - eapply c_trans; eassumption.
  - rewrite <- !app_assoc. apply c_rel. assumption.
Qed.

Lemma cong_app_l : forall R x y z, cong R x y -> cong R (z ++ x) (z ++ y).
Proof.
  intros R x y z H. induction H.
  - apply c_refl.
  - apply c_sym; assumption.
  - eapply c_trans; eassumption.
  - rewrite !(app_assoc z x). apply c_rel. assumption.
Qed.

Lemma cong_app : forall R x x' y y', cong R x x' -> cong R y y' -> cong R (x ++ y) (x' ++ y').
Proof.
  intros R x x' y y' Hx Hy. apply (c_trans R _ (x' ++ y) _).
  - apply cong_app_r; exact Hx.
  - apply cong_app_l; exact Hy.
Qed.

Lemma cong_rel : forall R l r, In (l, r) R -> cong R l r.
Proof.
  intros R l r H. pose proof (c_rel R [] l r [] H) as C.
  simpl in C. rewrite !app_nil_r in C. exact C.
Qed.

(** ** 2. The one-object model on words modulo the congruence
    One 0-cell [Ob]. [Ar j w] is the j-fold identity on the 1-cell given
    by the word w; it has dimension j+1. *)
Section MonoidModel.
Variable R : list (word * word).

Inductive MC : Type := Ob | Ar (j : nat) (w : word).

Definition meq (a b : MC) : Prop :=
  match a, b with
  | Ob, Ob => True
  | Ar j w, Ar j' w' => j = j' /\ cong R w w'
  | _, _ => False
  end.

Definition mdim (a : MC) : nat := match a with Ob => 0 | Ar j _ => S j end.
Definition msrc (a : MC) : MC :=
  match a with Ob => Ob | Ar 0 _ => Ob | Ar (S j) w => Ar j w end.
Definition mid (a : MC) : MC := match a with Ob => Ar 0 [] | Ar j w => Ar (S j) w end.
Definition mcomp (k : nat) (a b : MC) : MC :=
  match a, b with
  | Ar j w, Ar _ w' => match k with 0 => Ar j (w ++ w') | S _ => a end
  | _, _ => a
  end.

Definition MonSig : OmegaSig := {|
  Cell := MC; ceq := meq; cdim := mdim; csrc := msrc; ctgt := msrc; cid := mid;
  ccomp := fun k a b _ _ _ => mcomp k a b |}.

Lemma meq_refl : forall a, meq a a.
Proof. intros [|j w]; simpl; [exact I | split; [reflexivity | apply c_refl]]. Qed.

Lemma meq_sym : forall a b, meq a b -> meq b a.
Proof.
  intros [|j w] [|j' w']; simpl; try tauto.
  intros [E C]. split; [symmetry; exact E | apply c_sym; exact C].
Qed.

Lemma meq_trans : forall a b c, meq a b -> meq b c -> meq a c.
Proof.
  intros [|j w] [|j' w'] [|j'' w'']; simpl; try tauto.
  intros [E C] [E' C']. split; [congruence | eapply c_trans; eassumption].
Qed.

Lemma msrc_iter_le : forall c j w, c <= j -> Nat.iter c msrc (Ar j w) = Ar (j - c) w.
Proof.
  induction c as [|c IH]; intros j w H; simpl.
  - rewrite Nat.sub_0_r. reflexivity.
  - rewrite IH by lia. destruct (j - c) as [|n] eqn:E; [lia |].
    simpl. f_equal. lia.
Qed.

Lemma msrc_iter_top : forall j w, Nat.iter (S j) msrc (Ar j w) = Ob.
Proof. intros j w. simpl. rewrite msrc_iter_le by lia. rewrite Nat.sub_diag. reflexivity. Qed.

Lemma mid_iter_Ar : forall c j w, Nat.iter c mid (Ar j w) = Ar (j + c) w.
Proof.
  induction c as [|c IH]; intros j w; simpl.
  - rewrite Nat.add_0_r. reflexivity.
  - rewrite IH. simpl. f_equal. lia.
Qed.

Lemma mid_iter_Ob : forall j, Nat.iter (S j) mid Ob = Ar j [].
Proof.
  intro j. rewrite iter_shift. simpl mid. rewrite mid_iter_Ar. reflexivity.
Qed.

Lemma mon_unit_r : forall k (a : MC), k < mdim a ->
  meq (mcomp k a (@cidext_src MonSig (mdim a - k) a)) a.
Proof.
  intros k [|j w] Hk; simpl in Hk; [lia |]. destruct k as [|k].
  - assert (E : @cidext_src MonSig (mdim (Ar j w) - 0) (Ar j w) = Ar j []).
    { unfold cidext_src.
      change (Nat.iter (S j) mid (Nat.iter (S j) msrc (Ar j w)) = Ar j []).
      rewrite msrc_iter_top, mid_iter_Ob. reflexivity. }
    rewrite E. simpl. split; [reflexivity | rewrite app_nil_r; apply c_refl].
  - destruct (@cidext_src MonSig (mdim (Ar j w) - S k) (Ar j w));
      simpl; split; try reflexivity; apply c_refl.
Qed.

Lemma mon_unit_l : forall k (a : MC), k < mdim a ->
  meq (mcomp k (@cidext_tgt MonSig (mdim a - k) a) a) a.
Proof.
  intros k [|j w] Hk; simpl in Hk; [lia |]. destruct k as [|k].
  - assert (E : @cidext_tgt MonSig (mdim (Ar j w) - 0) (Ar j w) = Ar j []).
    { unfold cidext_tgt.
      change (Nat.iter (S j) mid (Nat.iter (S j) msrc (Ar j w)) = Ar j []).
      rewrite msrc_iter_top, mid_iter_Ob. reflexivity. }
    rewrite E. simpl. split; [reflexivity | apply c_refl].
  - assert (E : @cidext_tgt MonSig (mdim (Ar j w) - S k) (Ar j w) = Ar j w).
    { unfold cidext_tgt.
      change (Nat.iter (S j - S k) mid (Nat.iter (S j - S k) msrc (Ar j w)) = Ar j w).
      rewrite msrc_iter_le by lia. rewrite mid_iter_Ar. f_equal. lia. }
    rewrite E. simpl. split; [reflexivity | apply c_refl].
Qed.

Theorem MonModel : IsEqCatModel MonSig.
Proof.
  constructor; simpl.
  - apply meq_refl.
  - apply meq_sym.
  - apply meq_trans.
  - intros [|j w] [|j' w']; simpl; try tauto. intros [E _]. congruence.
  - intros [|[|j] w] [|[|j'] w']; simpl; try tauto; try lia;
      intros _ [E C]; try discriminate; try exact I.
    split; [congruence | exact C].
  - intros [|[|j] w] [|[|j'] w']; simpl; try tauto; try lia;
      intros _ [E C]; try discriminate; try exact I.
    split; [congruence | exact C].
  - intros [|j w] [|j' w']; simpl; try tauto.
    + intros _. split; [reflexivity | apply c_refl].
    + intros [E C]. split; [congruence | exact C].
  - intros k [|j w] [|j1 w1] [|j' w'] [|j1' w1'] H1 H2 H3 H1' H2' H3'; simpl in *;
      try tauto; try lia.
    intros [E C] [E1 C1]. destruct k; simpl.
    + split; [exact E | apply cong_app; assumption].
    + split; assumption.
  - intros [|[|j] w]; simpl; lia.
  - intros [|[|j] w]; simpl; lia.
  - intros [|j w]; reflexivity.
  - intros k [|j w] [|j' w'] H1 H2 H3; simpl in *; try lia; destruct k; reflexivity.
  - intros [|[|[|j]] w]; simpl; try lia; intros _; split; [reflexivity | apply c_refl].
  - intros [|[|[|j]] w]; simpl; try lia; intros _; split; [reflexivity | apply c_refl].
  - intros [|j w]; simpl; [exact I | split; [reflexivity | apply c_refl]].
  - intros [|j w]; simpl; [exact I | split; [reflexivity | apply c_refl]].
  - (* src of composite, top *)
    intros k [|j w] [|j' w'] H1 H2 H3 Hd; simpl in H1, H2, Hd; try lia.
    injection Hd as ->. injection H1 as <-.
    destruct k as [|k]; simpl; [exact I |].
    assert (H3' : meq (Nat.iter 1 msrc (Ar (S k) w)) (Nat.iter 1 msrc (Ar (S k) w'))).
    { replace 1 with (S (S k) - S k) by lia. exact H3. }
    simpl in H3'. exact H3'.
  - (* tgt of composite, top *)
    intros k [|j w] [|j' w'] H1 H2 H3 Hd; simpl in *; try lia.
    injection Hd as ->. destruct k as [|k]; simpl; [exact I | apply (meq_refl (Ar k w))].
  - (* src of composite, low *)
    intros k [|j w] [|j' w'] H1 H2 H3 H1' H2' H3' Hd; simpl in *; try lia.
    injection H1 as <-. destruct j as [|j]; [lia |].
    destruct k as [|k]; simpl; split; try reflexivity; apply c_refl.
  - (* tgt of composite, low *)
    intros k [|j w] [|j' w'] H1 H2 H3 H1' H2' H3' Hd; simpl in *; try lia.
    injection H1 as <-. destruct j as [|j]; [lia |].
    destruct k as [|k]; simpl; split; try reflexivity; apply c_refl.
  - (* assoc *)
    intros k [|ja wa] [|jb wb] [|jc wc] Hab1 Hab2 Hab3 Hl1 Hl2 Hl3 Hbc1 Hbc2 Hbc3 Hr1 Hr2 Hr3;
      simpl in *; try lia.
    destruct k as [|k]; simpl.
    + split; [reflexivity | rewrite app_assoc; apply c_refl].
    + split; [reflexivity | apply c_refl].
  - (* exchange *)
    intros m n [|jx wx] [|jy wy] [|jz wz] [|jw ww]
      Hxy1 Hxy2 Hxy3 Hzw1 Hzw2 Hzw3 HL1 HL2 HL3 Hxz1 Hxz2 Hxz3 Hyw1 Hyw2 Hyw3 HR1 HR2 HR3 Hmn;
      simpl in *; try lia.
    destruct m as [|m], n as [|n]; simpl; try lia;
      split; try reflexivity; apply c_refl.
  - (* unit r *)
    intros k a H1 H2 H3. exact (mon_unit_r k a H2).
  - (* unit l *)
    intros k a H1 H2 H3. apply (mon_unit_l k a). rewrite <- H1. exact H2.
  - (* id of composite *)
    intros k [|j w] [|j' w'] H1 H2 H3 H1' H2' H3'; simpl in *; try lia.
    destruct k as [|k]; simpl; split; try reflexivity; apply c_refl.
Qed.

End MonoidModel.

(** ** 3. Generators and terms
    One 0-dimensional generator (the base point) and one 1-dimensional
    generator for each letter. *)
Module LG <: GEN.
  Definition Generator := option letter.
  Definition gen_dim (g : Generator) : nat := match g with None => 0 | Some _ => 1 end.
  Definition Generator_eq_dec : forall g1 g2 : Generator, {g1 = g2} + {g1 <> g2}.
  Proof. decide equality. apply letter_eq_dec. Defined.
End LG.
Module U := UniversalF LG.
Import U.

Definition star : Term := gen None.
Definition lt (a : letter) : Term := gen (Some a).
Definition unit1 : Term := id star.

(** The term of a word: a1 ∘_0 (a2 ∘_0 (... ∘_0 id star)). *)
Fixpoint W (w : word) : Term :=
  match w with
  | [] => unit1
  | a :: w' => comp 0 (lt a) (W w')
  end.

(** Defined exactly when the letter a is a loop on the base point. *)
Definition guardL (a : letter) : Term :=
  id (src (comp 0 unit1 (comp 0 (lt a) unit1))).

(** The paper's encoding of a relation l = r: id l ∘_1 id r. *)
Definition relT (p : word * word) : Term := comp 1 (id (W (fst p))) (id (W (snd p))).

(** Defined exactly when [relT p] is; its value is id star. *)
Definition guardR (p : word * word) : Term := id (src (src (relT p))).

Definition seq (gs : list Term) : Term := fold_right (comp 0) unit1 gs.

(** The encoding of a presentation. *)
Definition enc (gens : list letter) (R : list (word * word)) : Term :=
  seq (map guardL gens ++ map guardR R).

Definition good (gens : list letter) (w : word) : Prop := Forall (fun a => In a gens) w.
Definition over (gens : list letter) (R : list (word * word)) : Prop :=
  forall l r, In (l, r) R -> good gens l /\ good gens r.

(** All these terms are well-formed 1-cells in the syntactic sense. *)
Lemma dim_W : forall w, dim (W w) = Some 1.
Proof.
  induction w as [|a w IH]; [reflexivity |].
  simpl W. apply dim_comp; [reflexivity | exact IH | lia].
Qed.

Lemma dim_guardL : forall a, dim (guardL a) = Some 1.
Proof. reflexivity. Qed.

Lemma dim_guardR : forall p, dim (guardR p) = Some 1.
Proof. intros [l r]. unfold guardR, relT. simpl. rewrite !dim_W. reflexivity. Qed.

Lemma dim_seq : forall gs, Forall (fun g => dim g = Some 1) gs -> dim (seq gs) = Some 1.
Proof.
  induction 1 as [|g gs Hg _ IH]; [reflexivity |].
  simpl seq. apply dim_comp; [exact Hg | exact IH | lia].
Qed.

Lemma dim_enc : forall gens R, dim (enc gens R) = Some 1.
Proof.
  intros gens R. apply dim_seq. apply Forall_app. split; apply Forall_forall; intros g Hg;
    apply in_map_iff in Hg; destruct Hg as (x & <- & _); [apply dim_guardL | apply dim_guardR].
Qed.

(** ** 4. The encoding in an arbitrary model *)
Section InModel.
Context (Sg : OmegaSig) (M : IsEqCatModel Sg).
Context (sigma : Generator -> Cell Sg).
Context (Hsig : forall g, cdim (sigma g) = gen_dim g).

Let sy := ceq_sym Sg M.
Let tr := ceq_trans Sg M.
Let rf := ceq_refl Sg M.
Let O := sigma None.
Let S (a : letter) := sigma (Some a).
Notation I := (Interp Sg sigma).
Notation dfd := (defined Sg sigma).

Lemma dO : cdim O = 0. Proof. apply (Hsig None). Qed.
Lemma dS : forall a, cdim (S a) = 1. Proof. intro a. apply (Hsig (Some a)). Qed.
Lemma dU : cdim (cid O) = 1. Proof. rewrite (cdim_id Sg M), dO. reflexivity. Qed.

(** Composability one level below the dimension is src x = tgt y. *)
Lemma comp1_inv : forall k (x y : Cell Sg), cdim x = Datatypes.S k ->
  ceq (Nat.iter (cdim x - k) csrc x) (Nat.iter (cdim x - k) ctgt y) ->
  ceq (csrc x) (ctgt y).
Proof. intros k x y Hd H. replace (cdim x - k) with 1 in H by lia. exact H. Qed.

Lemma I_gen_inv : forall g c, I (gen g) c -> c = sigma g.
Proof. intros g c H. inversion H. reflexivity. Qed.

Lemma I_unit1 : I unit1 (cid O).
Proof. apply I_id. apply I_gen. Qed.

Lemma I_unit1_inv : forall c, I unit1 c -> c = cid O.
Proof.
  intros c H. destruct (Interp_id_inv Sg sigma _ _ H) as (x & -> & Hx).
  rewrite (I_gen_inv _ _ Hx). reflexivity.
Qed.

(** A 1-cell that is a loop on the base point. *)
Definition isloop (c : Cell Sg) : Prop := cdim c = 1 /\ ceq (csrc c) O /\ ceq (ctgt c) O.
Definition loop (a : letter) : Prop := ceq (csrc (S a)) O /\ ceq (ctgt (S a)) O.

Lemma unit_isloop : isloop (cid O).
Proof. split; [apply dU | split; [apply (src_id Sg M) | apply (tgt_id Sg M)]]. Qed.

Lemma isloop_ceq : forall c c', isloop c -> ceq c c' -> isloop c'.
Proof.
  intros c c' (Hd & Hs & Ht) E. split; [rewrite <- (cdim_ceq Sg M _ _ E); exact Hd | split].
  - apply (tr _ (csrc c) _); [apply sy; apply (csrc_ceq Sg M); [lia | exact E] | exact Hs].
  - apply (tr _ (ctgt c) _); [apply sy; apply (ctgt_ceq Sg M); [lia | exact E] | exact Ht].
Qed.

Lemma loops_composable : forall x y, isloop x -> isloop y -> composable Sg 0 x y.
Proof.
  intros x y (Dx & Sx & Tx) (Dy & Sy & Ty).
  apply (comp1_ok Sg 0 x y Dx Dy). apply (tr _ O _); [exact Sx | apply sy; exact Ty].
Qed.

Lemma comp_isloop : forall x y H1 H2 H3, isloop x -> isloop y -> isloop (ccomp 0 x y H1 H2 H3).
Proof.
  intros x y H1 H2 H3 (Dx & Sx & Tx) (Dy & Sy & Ty). split; [| split].
  - rewrite (cdim_comp Sg M). exact Dx.
  - apply (tr _ (csrc y) _); [apply (src_comp_top Sg M); exact Dx | exact Sy].
  - apply (tr _ (ctgt x) _); [apply (tgt_comp_top Sg M); exact Dx | exact Tx].
Qed.

Lemma letter_isloop : forall a, loop a -> isloop (S a).
Proof. intros a [Hs Ht]. split; [apply dS | split; assumption]. Qed.

(** Words. *)
Lemma W_defined : forall w, Forall loop w -> exists c, I (W w) c /\ isloop c.
Proof.
  induction 1 as [|a w Ha _ IH].
  - exists (cid O). split; [apply I_unit1 | apply unit_isloop].
  - destruct IH as (c & Hc & Lc).
    destruct (loops_composable (S a) c (letter_isloop a Ha) Lc) as (P1 & P2 & P3).
    exists (ccomp 0 (S a) c P1 P2 P3). split.
    + simpl W. apply I_comp; [apply I_gen | exact Hc].
    + apply comp_isloop; [apply letter_isloop; exact Ha | exact Lc].
Qed.

Lemma W_isloop : forall w c, Forall loop w -> I (W w) c -> isloop c.
Proof.
  intros w c Hw Hc. destruct (W_defined w Hw) as (c' & Hc' & L).
  apply (isloop_ceq c' c L). apply (Interp_fun Sg M sigma _ _ Hc' _ Hc).
Qed.

Lemma W_cdim : forall w c, I (W w) c -> cdim c = 1.
Proof.
  intros w c H. pose proof (Interp_dim Sg M sigma Hsig _ _ H) as D.
  rewrite dim_W in D. injection D as D. symmetry; exact D.
Qed.

(** The letter guard. *)
Lemma guardL_defined : forall a, dfd (guardL a) -> loop a.
Proof.
  intros a [c H]. unfold guardL in H.
  destruct (Interp_id_inv Sg sigma _ _ H) as (x & _ & Hx).
  destruct (Interp_src_inv Sg sigma _ _ Hx) as (y & _ & Hy & _).
  destruct (Interp_comp_inv Sg sigma _ _ _ _ Hy) as (p & q & H1 & H2 & H3 & _ & Hp & Hq).
  destruct (Interp_comp_inv Sg sigma _ _ _ _ Hq) as (s & e & K1 & K2 & K3 & -> & Hs & He).
  apply I_unit1_inv in Hp. apply I_unit1_inv in He. apply I_gen_inv in Hs. subst p e s.
  fold (S a) in *.
  pose proof (comp1_inv 0 (S a) (cid O) (dS a) K3) as B1.
  pose proof (comp1_inv 0 (cid O) _ dU H3) as B2.
  split.
  - apply (tr _ (ctgt (cid O)) _); [exact B1 | apply (tgt_id Sg M)].
  - apply sy. apply (tr _ (csrc (cid O)) _); [apply sy; apply (src_id Sg M) |].
    apply (tr _ _ _ B2). apply (tgt_comp_top Sg M). apply dS.
Qed.

Lemma guardL_value : forall a, loop a -> exists c, I (guardL a) c /\ ceq c (cid O).
Proof.
  intros a La. pose proof (letter_isloop a La) as LS.
  destruct (loops_composable (S a) (cid O) LS unit_isloop) as (P1 & P2 & P3).
  set (inner := ccomp 0 (S a) (cid O) P1 P2 P3).
  assert (Li : isloop inner) by (apply comp_isloop; [exact LS | apply unit_isloop]).
  destruct (loops_composable (cid O) inner unit_isloop Li) as (Q1 & Q2 & Q3).
  set (outer := ccomp 0 (cid O) inner Q1 Q2 Q3).
  assert (Lo : isloop outer) by (apply comp_isloop; [apply unit_isloop | exact Li]).
  exists (cid (csrc outer)). split.
  - unfold guardL. apply I_id. apply I_src.
    + apply I_comp; [apply I_unit1 | apply I_comp; [apply I_gen | apply I_unit1]].
    + destruct Lo as (D & _). lia.
  - apply (cid_ceq Sg M). destruct Lo as (_ & Hs & _). exact Hs.
Qed.

(** The relation guard. *)
Lemma guardR_defined : forall l r, dfd (guardR (l, r)) ->
  forall cl cr, I (W l) cl -> I (W r) cr -> ceq cl cr.
Proof.
  intros l r [c H] cl cr Hl Hr. unfold guardR, relT in H. simpl fst in H. simpl snd in H.
  destruct (Interp_id_inv Sg sigma _ _ H) as (x & _ & Hx).
  destruct (Interp_src_inv Sg sigma _ _ Hx) as (y & _ & Hy & _).
  destruct (Interp_src_inv Sg sigma _ _ Hy) as (z & _ & Hz & _).
  destruct (Interp_comp_inv Sg sigma _ _ _ _ Hz) as (p & q & H1 & H2 & H3 & _ & Hp & Hq).
  destruct (Interp_id_inv Sg sigma _ _ Hp) as (pl & -> & Hpl).
  destruct (Interp_id_inv Sg sigma _ _ Hq) as (qr & -> & Hqr).
  assert (Dp : cdim (cid pl) = 2) by (rewrite (cdim_id Sg M), (W_cdim l pl Hpl); reflexivity).
  pose proof (comp1_inv 1 (cid pl) (cid qr) Dp H3) as B.
  apply (tr _ pl _); [apply (Interp_fun Sg M sigma _ _ Hl _ Hpl) |].
  apply (tr _ qr _); [| apply (Interp_fun Sg M sigma _ _ Hqr _ Hr)].
  apply (tr _ (csrc (cid pl)) _); [apply sy; apply (src_id Sg M) |].
  apply (tr _ _ _ B). apply (tgt_id Sg M).
Qed.

Lemma guardR_value : forall l r, Forall loop l -> Forall loop r ->
  (forall cl cr, I (W l) cl -> I (W r) cr -> ceq cl cr) ->
  exists c, I (guardR (l, r)) c /\ ceq c (cid O).
Proof.
  intros l r Ll Lr Hh.
  destruct (W_defined l Ll) as (cl & Hl & (Dl & _ & _)).
  destruct (W_defined r Lr) as (cr & Hr & (Dr & Sr & _)).
  pose proof (Hh cl cr Hl Hr) as E.
  assert (Dp : cdim (cid cl) = 2) by (rewrite (cdim_id Sg M), Dl; reflexivity).
  assert (Dq : cdim (cid cr) = 2) by (rewrite (cdim_id Sg M), Dr; reflexivity).
  assert (B : ceq (csrc (cid cl)) (ctgt (cid cr))).
  { apply (tr _ cl _); [apply (src_id Sg M) |].
    apply (tr _ cr _); [exact E | apply sy; apply (tgt_id Sg M)]. }
  destruct (comp1_ok Sg 1 (cid cl) (cid cr) Dp Dq B) as (P1 & P2 & P3).
  set (y := ccomp 1 (cid cl) (cid cr) P1 P2 P3).
  assert (Dy : cdim y = 2) by (unfold y; rewrite (cdim_comp Sg M); exact Dp).
  assert (Sy : ceq (csrc y) cr).
  { apply (tr _ (csrc (cid cr)) _); [apply (src_comp_top Sg M); exact Dp | apply (src_id Sg M)]. }
  assert (Dsy : cdim (csrc y) = 1) by (rewrite (cdim_src Sg M); lia).
  exists (cid (csrc (csrc y))). split.
  - unfold guardR, relT. simpl fst. simpl snd.
    apply I_id. apply I_src; [apply I_src; [| lia] | lia].
    apply I_comp; apply I_id; assumption.
  - apply (cid_ceq Sg M). apply (tr _ (csrc cr) _); [| exact Sr].
    apply (csrc_ceq Sg M); [lia | exact Sy].
Qed.

(** Sequences of guards. *)
Lemma seq_defined : forall gs, dfd (seq gs) -> Forall (fun g => dfd g) gs.
Proof.
  induction gs as [|g gs IH]; intros [c H]; [constructor |].
  simpl seq in H.
  destruct (Interp_comp_inv Sg sigma _ _ _ _ H) as (x & y & _ & _ & _ & _ & Hx & Hy).
  constructor; [exists x; exact Hx | apply IH; exists y; exact Hy].
Qed.

Lemma seq_value : forall gs,
  Forall (fun g => exists c, I g c /\ ceq c (cid O)) gs ->
  exists c, I (seq gs) c /\ ceq c (cid O).
Proof.
  induction 1 as [|g gs (x & Hx & Ex) _ (y & Hy & Ey)].
  - exists (cid O). split; [apply I_unit1 | apply rf].
  - pose proof (loops_composable (cid O) (cid O) unit_isloop unit_isloop) as C0.
    destruct (composable_ceq Sg M 0 _ _ x y C0 (sy _ _ Ex) (sy _ _ Ey)) as (P1 & P2 & P3).
    destruct C0 as (Q1 & Q2 & Q3).
    exists (ccomp 0 x y P1 P2 P3). split.
    + simpl seq. apply I_comp; assumption.
    + apply (tr _ (ccomp 0 (cid O) (cid O) Q1 Q2 Q3) _).
      * apply (ccomp_ceq Sg M); assumption.
      * apply (unit_l1' Sg M 0 (cid O) O dU). apply sy. apply (tgt_id Sg M).
Qed.

(** A model satisfies the relations of R under sigma. *)
Definition holds (R : list (word * word)) : Prop :=
  forall l r, In (l, r) R -> forall cl cr, I (W l) cl -> I (W r) cr -> ceq cl cr.

Lemma good_loops : forall gens w, Forall loop gens -> good gens w -> Forall loop w.
Proof.
  intros gens w Hg Hw. apply Forall_forall. intros a Ha.
  apply (proj1 (Forall_forall _ _) Hg). apply (proj1 (Forall_forall _ _) Hw). exact Ha.
Qed.

(** The encoding of a presentation is defined exactly when the generators
    are loops on the base point and the relations hold; its value is then
    the identity of the base point. *)
Lemma enc_defined : forall gens R, dfd (enc gens R) -> Forall loop gens /\ holds R.
Proof.
  intros gens R H. apply seq_defined in H. apply Forall_app in H. destruct H as [HL HR].
  split.
  - apply Forall_forall. intros a Ha. apply guardL_defined.
    apply (proj1 (Forall_forall _ _) HL). apply in_map. exact Ha.
  - intros l r Hin. apply guardR_defined.
    apply (proj1 (Forall_forall _ _) HR). apply (in_map guardR R (l, r)). exact Hin.
Qed.

Lemma enc_value : forall gens R, over gens R -> Forall loop gens -> holds R ->
  exists c, I (enc gens R) c /\ ceq c (cid O).
Proof.
  intros gens R Hov HL HR. apply seq_value. apply Forall_app. split; apply Forall_forall; intros g Hg;
    apply in_map_iff in Hg.
  - destruct Hg as (a & <- & Ha). apply guardL_value.
    apply (proj1 (Forall_forall _ _) HL). exact Ha.
  - destruct Hg as ([l r] & <- & Hin). destruct (Hov l r Hin) as [Gl Gr].
    apply guardR_value; [apply (good_loops gens); assumption | apply (good_loops gens); assumption |].
    apply (HR l r Hin).
Qed.

Lemma enc_is_unit : forall gens R c, over gens R -> I (enc gens R) c -> ceq c (cid O).
Proof.
  intros gens R c Hov Hc.
  destruct (enc_defined gens R (ex_intro _ c Hc)) as [HL HR].
  destruct (enc_value gens R Hov HL HR) as (c' & Hc' & E).
  apply (tr _ c' _); [apply (Interp_fun Sg M sigma _ _ Hc _ Hc') | exact E].
Qed.

(** Concatenation of words is composition. *)
Lemma W_app : forall x y c cx cy, Forall loop x -> Forall loop y ->
  I (W (x ++ y)) c -> I (W x) cx -> I (W y) cy ->
  forall H1 H2 H3, ceq c (ccomp 0 cx cy H1 H2 H3).
Proof.
  induction x as [|a x IH]; intros y c cx cy Lx Ly Hc Hx Hy H1 H2 H3.
  - simpl in Hc, Hx. apply I_unit1_inv in Hx. subst cx.
    apply (tr _ cy _); [apply (Interp_fun Sg M sigma _ _ Hc _ Hy) |].
    apply sy. apply (unit_l1' Sg M 0 cy O).
    + destruct (W_isloop y cy Ly Hy) as (D & _); exact D.
    + destruct (W_isloop y cy Ly Hy) as (_ & _ & T). apply sy; exact T.
  - simpl in Hc, Hx. inversion Lx as [|a' x' La Lx']; subst.
    destruct (Interp_comp_inv Sg sigma _ _ _ _ Hc) as (s & c' & A1 & A2 & A3 & -> & Hs & Hc').
    destruct (Interp_comp_inv Sg sigma _ _ _ _ Hx) as (s' & cx' & B1 & B2 & B3 & -> & Hs' & Hx').
    apply I_gen_inv in Hs. apply I_gen_inv in Hs'. subst s s'. fold (S a) in *.
    pose proof (W_isloop x cx' Lx' Hx') as Lcx.
    pose proof (W_isloop y cy Ly Hy) as Lcy.
    destruct (loops_composable cx' cy Lcx Lcy) as (P1 & P2 & P3).
    pose proof (IH y c' cx' cy Lx' Ly Hc' Hx' Hy P1 P2 P3) as E.
    assert (Lin : isloop (ccomp 0 cx' cy P1 P2 P3)) by (apply comp_isloop; assumption).
    destruct (loops_composable (S a) _ (letter_isloop a La) Lin) as (Q1 & Q2 & Q3).
    apply (tr _ (ccomp 0 (S a) (ccomp 0 cx' cy P1 P2 P3) Q1 Q2 Q3) _).
    + apply (ccomp_ceq Sg M); [apply rf | exact E].
    + apply sy. apply (assoc Sg M).
Qed.

(** If the relations of R hold in the model, so does everything in the
    congruence they generate, on words over the generators. *)
Lemma cong_sound : forall gens R, over gens R -> Forall loop gens -> holds R ->
  forall x y, cong R x y ->
  (good gens x <-> good gens y) /\
  (good gens x -> forall cx cy, I (W x) cx -> I (W y) cy -> ceq cx cy).
Proof.
  intros gens R Hov HL HR x y H.
  induction H as [x | x y _ [IHg IHv] | x y z _ [IHg1 IHv1] _ [IHg2 IHv2] | x l r y Hin].
  - split; [tauto |]. intros _ cx cy Hx Hy. apply (Interp_fun Sg M sigma _ _ Hx _ Hy).
  - split; [tauto |]. intros Gy cx cy Hx Hy. apply sy. apply IHv; [tauto | assumption | assumption].
  - split; [tauto |]. intros Gx cx cz Hx Hz.
    assert (Gy : good gens y) by tauto.
    destruct (W_defined y (good_loops gens y HL Gy)) as (cy & Hy & _).
    apply (tr _ cy _); [apply IHv1 | apply IHv2]; assumption.
  - destruct (Hov l r Hin) as [Gl Gr].
    assert (Gsplit : forall m, good gens (x ++ m ++ y) <-> good gens x /\ good gens m /\ good gens y).
    { intro m. unfold good. rewrite !Forall_app. tauto. }
    split; [rewrite !Gsplit; tauto |].
    intros G cx cy Hx Hy. apply Gsplit in G. destruct G as (Gx & _ & Gy).
    pose proof (good_loops gens x HL Gx) as Lx. pose proof (good_loops gens y HL Gy) as Ly.
    pose proof (good_loops gens l HL Gl) as Ll. pose proof (good_loops gens r HL Gr) as Lr.
    destruct (W_defined x Lx) as (ax & Hax & Lax).
    destruct (W_defined y Ly) as (ay & Hay & Lay).
    destruct (W_defined l Ll) as (al & Hal & Lal).
    destruct (W_defined r Lr) as (ar & Har & Lar).
    destruct (W_defined (l ++ y) ltac:(apply Forall_app; split; assumption)) as (aly & Haly & Laly).
    destruct (W_defined (r ++ y) ltac:(apply Forall_app; split; assumption)) as (ary & Hary & Lary).
    destruct (loops_composable al ay Lal Lay) as (P1 & P2 & P3).
    destruct (loops_composable ar ay Lar Lay) as (Q1 & Q2 & Q3).
    assert (E1 : ceq aly ary).
    { apply (tr _ (ccomp 0 al ay P1 P2 P3) _); [apply (W_app l y); assumption |].
      apply (tr _ (ccomp 0 ar ay Q1 Q2 Q3) _); [| apply sy; apply (W_app r y); assumption].
      apply (ccomp_ceq Sg M); [apply (HR l r Hin); assumption | apply rf]. }
    destruct (loops_composable ax aly Lax Laly) as (S1 & S2 & S3).
    destruct (loops_composable ax ary Lax Lary) as (T1 & T2 & T3).
    apply (tr _ (ccomp 0 ax aly S1 S2 S3) _).
    + apply (W_app x (l ++ y)); try assumption. apply Forall_app; split; assumption.
    + apply (tr _ (ccomp 0 ax ary T1 T2 T3) _).
      * apply (ccomp_ceq Sg M); [apply rf | exact E1].
      * apply sy. apply (W_app x (r ++ y)); try assumption. apply Forall_app; split; assumption.
Qed.

(** Composing a loop with a cell equal to the unit does nothing. *)
Lemma unit_absorb : forall cu g H1 H2 H3,
  isloop cu -> ceq g (cid O) -> ceq (ccomp 0 cu g H1 H2 H3) cu.
Proof.
  intros cu g H1 H2 H3 (D & Hs & _) E.
  destruct (composable_ceq Sg M 0 cu g cu (cid O) (conj H1 (conj H2 H3)) (rf cu) E) as (P1 & P2 & P3).
  apply (tr _ (ccomp 0 cu (cid O) P1 P2 P3) _).
  - apply (ccomp_ceq Sg M); [apply rf | exact E].
  - apply (unit_r1' Sg M 0 cu O D). apply sy. exact Hs.
Qed.

(** If the relations of R2 follow from those of R1, then wherever the
    encoding of R1 is defined so is the encoding of R2. *)
Lemma enc_transfer : forall gens R1 R2, over gens R1 -> over gens R2 ->
  (forall l r, In (l, r) R2 -> cong R1 l r) ->
  dfd (enc gens R1) -> exists c, I (enc gens R2) c /\ ceq c (cid O).
Proof.
  intros gens R1 R2 Hov1 Hov2 C D.
  destruct (enc_defined gens R1 D) as [HL HR1].
  apply (enc_value gens R2 Hov2 HL).
  intros l r Hin cl cr Hl Hr.
  destruct (cong_sound gens R1 Hov1 HL HR1 l r (C l r Hin)) as [_ V].
  apply V; [destruct (Hov2 l r Hin); assumption | assumption | assumption].
Qed.

End InModel.

(** ** 5. The two readings of EQ *)

(** The text's definition: equal whenever both sides are defined. *)
Definition InEQ_weak (e1 e2 : Term) : Prop :=
  forall (Sg : OmegaSig), IsEqCatModel Sg ->
  forall sigma : Generator -> Cell Sg, (forall g, cdim (sigma g) = gen_dim g) ->
  forall c1 c2, Interp Sg sigma e1 c1 -> Interp Sg sigma e2 c2 -> ceq c1 c2.

(** The commented-out definition: defined together, and equal when defined. *)
Definition InEQ_strong (e1 e2 : Term) : Prop :=
  forall (Sg : OmegaSig), IsEqCatModel Sg ->
  forall sigma : Generator -> Cell Sg, (forall g, cdim (sigma g) = gen_dim g) ->
  same Sg sigma e1 e2.

(** ** 6. The word model of a presentation *)
Definition sigmaM (R : list (word * word)) : Generator -> Cell (MonSig R) :=
  fun g => match g with None => Ob | Some a => Ar 0 [a] end.

Lemma sigmaM_dim : forall R g, cdim (sigmaM R g) = gen_dim g.
Proof. intros R [a|]; reflexivity. Qed.

Lemma W_mon : forall R w, Interp (MonSig R) (sigmaM R) (W w) (Ar 0 w).
Proof.
  intros R. induction w as [|a w IH].
  - exact (I_id (MonSig R) (sigmaM R) _ _ (I_gen (MonSig R) (sigmaM R) None)).
  - assert (P : composable (MonSig R) 0 (Ar 0 [a]) (Ar 0 w)).
    { split; [reflexivity | split; [simpl; lia | simpl; exact Logic.I]]. }
    destruct P as (P1 & P2 & P3).
    exact (I_comp (MonSig R) (sigmaM R) 0 (lt a) (W w) (Ar 0 [a]) (Ar 0 w) P1 P2 P3
             (I_gen (MonSig R) (sigmaM R) (Some a)) IH).
Qed.

Lemma mon_loops : forall R gens, Forall (loop (MonSig R) (sigmaM R)) gens.
Proof. intros R gens. apply Forall_forall. intros a _. split; simpl; exact Logic.I. Qed.

Lemma mon_holds : forall R R',
  holds (MonSig R) (sigmaM R) R' <-> (forall l r, In (l, r) R' -> cong R l r).
Proof.
  intros R R'. split.
  - intros H l r Hin. exact (proj2 (H l r Hin (Ar 0 l) (Ar 0 r) (W_mon R l) (W_mon R r))).
  - intros H l r Hin cl cr Hl Hr.
    apply (ceq_trans (MonSig R) (MonModel R) _ (Ar 0 l) _).
    + apply (Interp_fun (MonSig R) (MonModel R) (sigmaM R) _ _ Hl _ (W_mon R l)).
    + apply (ceq_trans (MonSig R) (MonModel R) _ (Ar 0 r) _).
      * split; [reflexivity | apply H; exact Hin].
      * apply (Interp_fun (MonSig R) (MonModel R) (sigmaM R) _ _ (W_mon R r) _ Hr).
Qed.

Lemma mon_enc : forall R gens R', over gens R' -> (forall l r, In (l, r) R' -> cong R l r) ->
  exists c, Interp (MonSig R) (sigmaM R) (enc gens R') c /\
            ceq c (cid (sigmaM R None)).
Proof.
  intros R gens R' Hov H.
  apply (enc_value (MonSig R) (MonModel R) (sigmaM R) (sigmaM_dim R) gens R' Hov).
  - apply mon_loops.
  - apply mon_holds. exact H.
Qed.

(** ** 7. The word problem, under the text's reading of EQ *)

(** u ∘_0 (encoding of the presentation). The second factor is defined
    exactly when the model satisfies the presentation, and is then a unit. *)
Definition wp_term (gens : list letter) (R : list (word * word)) (u : word) : Term :=
  comp 0 (W u) (enc gens R).

Lemma dim_wp_term : forall gens R u, dim (wp_term gens R u) = Some 1.
Proof. intros. unfold wp_term. apply dim_comp; [apply dim_W | apply dim_enc | lia]. Qed.

Theorem word_problem_reduces : forall gens R u v,
  over gens R -> good gens u -> good gens v ->
  (cong R u v <-> InEQ_weak (wp_term gens R u) (wp_term gens R v)).
Proof.
  intros gens R u v Hov Gu Gv. split.
  - intros C Sg M sigma Hsig c1 c2 H1 H2. unfold wp_term in *.
    destruct (Interp_comp_inv Sg sigma _ _ _ _ H1) as (cu & g & A1 & A2 & A3 & -> & Hu & Hg).
    destruct (Interp_comp_inv Sg sigma _ _ _ _ H2) as (cv & g' & B1 & B2 & B3 & -> & Hv & Hg').
    destruct (enc_defined Sg M sigma Hsig gens R (ex_intro _ g Hg)) as [HL HR].
    pose proof (enc_is_unit Sg M sigma Hsig gens R g Hov Hg) as Eg.
    pose proof (enc_is_unit Sg M sigma Hsig gens R g' Hov Hg') as Eg'.
    pose proof (W_isloop Sg M sigma Hsig u cu (good_loops Sg sigma gens u HL Gu) Hu) as Lu.
    pose proof (W_isloop Sg M sigma Hsig v cv (good_loops Sg sigma gens v HL Gv) Hv) as Lv.
    apply (ceq_trans Sg M _ cu _); [apply (unit_absorb Sg M sigma); assumption |].
    apply (ceq_trans Sg M _ cv _); [| apply (ceq_sym Sg M); apply (unit_absorb Sg M sigma); assumption].
    destruct (cong_sound Sg M sigma Hsig gens R Hov HL HR u v C) as [_ V].
    apply V; assumption.
  - intro H.
    destruct (mon_enc R gens R Hov (cong_rel R)) as (g & Hg & Eg).
    pose proof (mon_loops R gens) as HL.
    pose proof (W_isloop _ (MonModel R) _ (sigmaM_dim R) u _ (good_loops _ _ gens u HL Gu) (W_mon R u)) as Lu.
    pose proof (W_isloop _ (MonModel R) _ (sigmaM_dim R) v _ (good_loops _ _ gens v HL Gv) (W_mon R v)) as Lv.
    assert (Lg : isloop (MonSig R) (sigmaM R) g).
    { apply (isloop_ceq _ (MonModel R) _ (cid (sigmaM R None)) g).
      - apply (unit_isloop _ (MonModel R) _ (sigmaM_dim R)).
      - apply (ceq_sym _ (MonModel R)). exact Eg. }
    destruct (loops_composable _ (MonModel R) _ _ _ Lu Lg) as (P1 & P2 & P3).
    destruct (loops_composable _ (MonModel R) _ _ _ Lv Lg) as (Q1 & Q2 & Q3).
    pose proof (H (MonSig R) (MonModel R) (sigmaM R) (sigmaM_dim R) _ _
                  (I_comp _ _ 0 _ _ _ _ P1 P2 P3 (W_mon R u) Hg)
                  (I_comp _ _ 0 _ _ _ _ Q1 Q2 Q3 (W_mon R v) Hg)) as E.
    assert (E' : ceq (Ar 0 u : Cell (MonSig R)) (Ar 0 v)).
    { apply (ceq_trans _ (MonModel R) _ (ccomp 0 (Ar 0 u : Cell (MonSig R)) g P1 P2 P3) _).
      - apply (ceq_sym _ (MonModel R)). apply (unit_absorb _ (MonModel R) (sigmaM R)); assumption.
      - apply (ceq_trans _ (MonModel R) _ _ _ E).
        apply (unit_absorb _ (MonModel R) (sigmaM R)); assumption. }
    exact (proj2 E').
Qed.

(** ** 8. Equivalence of presentations and triviality, under the strong reading *)

Theorem presentations_reduce : forall gens R1 R2, over gens R1 -> over gens R2 ->
  (InEQ_strong (enc gens R1) (enc gens R2) <->
   (forall l r, In (l, r) R2 -> cong R1 l r) /\ (forall l r, In (l, r) R1 -> cong R2 l r)).
Proof.
  intros gens R1 R2 Hov1 Hov2. split.
  - intro H. split.
    + destruct (H (MonSig R1) (MonModel R1) (sigmaM R1) (sigmaM_dim R1)) as [S1 _].
      destruct (mon_enc R1 gens R1 Hov1 (cong_rel R1)) as (g & Hg & _).
      destruct (S1 g Hg) as (g' & Hg' & _).
      destruct (enc_defined _ (MonModel R1) _ (sigmaM_dim R1) gens R2 (ex_intro _ g' Hg')) as [_ HR].
      apply mon_holds. exact HR.
    + destruct (H (MonSig R2) (MonModel R2) (sigmaM R2) (sigmaM_dim R2)) as [_ S2].
      destruct (mon_enc R2 gens R2 Hov2 (cong_rel R2)) as (g & Hg & _).
      destruct (S2 g Hg) as (g' & Hg' & _).
      destruct (enc_defined _ (MonModel R2) _ (sigmaM_dim R2) gens R1 (ex_intro _ g' Hg')) as [_ HR].
      apply mon_holds. exact HR.
  - intros [C21 C12] Sg M sigma Hsig. split; intros c Hc.
    + destruct (enc_transfer Sg M sigma Hsig gens R1 R2 Hov1 Hov2 C21 (ex_intro _ c Hc))
        as (c' & Hc' & E').
      exists c'. split; [exact Hc' |].
      apply (ceq_trans Sg M _ (cid (sigma None)) _).
      * apply (enc_is_unit Sg M sigma Hsig gens R1 c Hov1 Hc).
      * apply (ceq_sym Sg M). exact E'.
    + destruct (enc_transfer Sg M sigma Hsig gens R2 R1 Hov2 Hov1 C12 (ex_intro _ c Hc))
        as (c' & Hc' & E').
      exists c'. split; [exact Hc' |].
      apply (ceq_trans Sg M _ (cid (sigma None)) _).
      * exact E'.
      * apply (ceq_sym Sg M). apply (enc_is_unit Sg M sigma Hsig gens R2 c Hov2 Hc).
Qed.

(** The presentation of the trivial monoid on the same generators. *)
Definition triv (gens : list letter) : list (word * word) := map (fun a => ([a], [])) gens.

Lemma over_triv : forall gens, over gens (triv gens).
Proof.
  intros gens l r Hin. apply in_map_iff in Hin. destruct Hin as (a & E & Ha).
  injection E as <- <-. split; [constructor; [exact Ha | constructor] | constructor].
Qed.

Lemma triv_collapses : forall gens w, good gens w -> cong (triv gens) w [].
Proof.
  intros gens w H. induction H as [|a w Ha _ IH]; [apply c_refl |].
  apply (c_trans _ _ w _); [| exact IH].
  apply (c_rel (triv gens) [] [a] [] w). apply (in_map (fun a => ([a], [])) gens a Ha).
Qed.

Theorem triviality_reduces : forall gens R, over gens R ->
  (InEQ_strong (enc gens R) (enc gens (triv gens)) <-> forall a, In a gens -> cong R [a] []).
Proof.
  intros gens R Hov.
  rewrite (presentations_reduce gens R (triv gens) Hov (over_triv gens)). split.
  - intros [H _] a Ha. apply H. apply (in_map (fun a => ([a], [])) gens a Ha).
  - intro H. split.
    + intros l r Hin. apply in_map_iff in Hin. destruct Hin as (a & E & Ha).
      injection E as <- <-. apply H. exact Ha.
    + intros l r Hin. destruct (Hov l r Hin) as [Gl Gr].
      apply (c_trans _ _ [] _); [apply triv_collapses; exact Gl |].
      apply c_sym. apply triv_collapses. exact Gr.
Qed.

(** Under the text's reading the same equation is in EQ for every pair of
    presentations: both sides are units whenever they are defined. *)
Theorem presentation_equation_weak : forall gens R1 R2, over gens R1 -> over gens R2 ->
  InEQ_weak (enc gens R1) (enc gens R2).
Proof.
  intros gens R1 R2 Hov1 Hov2 Sg M sigma Hsig c1 c2 H1 H2.
  apply (ceq_trans Sg M _ (cid (sigma None)) _).
  - apply (enc_is_unit Sg M sigma Hsig gens R1 c1 Hov1 H1).
  - apply (ceq_sym Sg M). apply (enc_is_unit Sg M sigma Hsig gens R2 c2 Hov2 H2).
Qed.

(** ** 9. The literal equation of the paper's proof, on one example
    One generator s and the relation s = s. The paper's equation is
        id s ∘_1 id s  =  id s ∘_1 id (id (src s)). *)
Definition paper_lhs (s : letter) : Term := comp 1 (id (lt s)) (id (lt s)).
Definition paper_rhs (s : letter) : Term := comp 1 (id (lt s)) (id (id (src (lt s)))).

Lemma cong_length : forall R, (forall l r, In (l, r) R -> length l = length r) ->
  forall x y, cong R x y -> length x = length y.
Proof.
  intros R HR x y H. induction H.
  - reflexivity.
  - symmetry; assumption.
  - congruence.
  - rewrite !app_length. rewrite (HR l r H). reflexivity.
Qed.

(** The presentation is not trivial. *)
Theorem paper_example_nontrivial : forall s, ~ cong [([s], [s])] [s] [].
Proof.
  intros s H. apply cong_length in H; [discriminate H |].
  intros l r [E | []]. injection E as <- <-. reflexivity.
Qed.

(** Under the text's reading its equation is in EQ all the same. *)
Theorem paper_equation_weak : forall s, InEQ_weak (paper_lhs s) (paper_rhs s).
Proof.
  intros s Sg M sigma Hsig c1 c2 H1 H2. unfold paper_lhs, paper_rhs in *.
  set (S := sigma (Some s)).
  assert (DS : cdim S = 1) by (apply (Hsig (Some s))).
  assert (D2 : cdim (cid S) = 2) by (rewrite (cdim_id Sg M), DS; reflexivity).
  destruct (Interp_comp_inv Sg sigma _ _ _ _ H1) as (p & q & A1 & A2 & A3 & -> & Hp & Hq).
  destruct (Interp_id_inv Sg sigma _ _ Hp) as (p0 & -> & Hp0).
  destruct (Interp_id_inv Sg sigma _ _ Hq) as (q0 & -> & Hq0).
  apply (I_gen_inv Sg sigma) in Hp0. apply (I_gen_inv Sg sigma) in Hq0. subst p0 q0.
  clear Hp Hq.
  destruct (Interp_comp_inv Sg sigma _ _ _ _ H2) as (p & q & B1 & B2 & B3 & -> & Hp & Hq).
  destruct (Interp_id_inv Sg sigma _ _ Hp) as (p0 & -> & Hp0).
  destruct (Interp_id_inv Sg sigma _ _ Hq) as (q0 & -> & Hq0).
  destruct (Interp_id_inv Sg sigma _ _ Hq0) as (q1 & -> & Hq1).
  destruct (Interp_src_inv Sg sigma _ _ Hq1) as (q2 & -> & Hq2 & _).
  apply (I_gen_inv Sg sigma) in Hp0. apply (I_gen_inv Sg sigma) in Hq2. subst p0 q2.
  pose proof (comp1_inv Sg 1 (cid S) _ D2 B3) as B.
  assert (ES : ceq S (cid (csrc S))).
  { apply (ceq_trans Sg M _ (csrc (cid S)) _); [apply (ceq_sym Sg M); apply (src_id Sg M) |].
    apply (ceq_trans Sg M _ _ _ B). apply (tgt_id Sg M). }
  apply (ceq_trans Sg M _ (cid S) _).
  - apply (unit_r1' Sg M 1 (cid S) S D2). apply (ceq_sym Sg M). apply (src_id Sg M).
  - apply (ceq_sym Sg M). apply (unit_r1' Sg M 1 (cid S) (cid (csrc S)) D2).
    apply (ceq_trans Sg M _ S _); [apply (ceq_sym Sg M); exact ES |].
    apply (ceq_sym Sg M). apply (src_id Sg M).
Qed.

(** Under the strong reading it is not in EQ, as the paper's proof needs. *)
Theorem paper_equation_not_strong : forall s, ~ InEQ_strong (paper_lhs s) (paper_rhs s).
Proof.
  intros s H. set (R0 := [([s], [s])]).
  destruct (H (MonSig R0) (MonModel R0) (sigmaM R0) (sigmaM_dim R0)) as [S1 _].
  assert (Hs : Interp (MonSig R0) (sigmaM R0) (id (lt s)) (Ar 1 [s])).
  { exact (I_id (MonSig R0) (sigmaM R0) _ _ (I_gen (MonSig R0) (sigmaM R0) (Some s))). }
  assert (P : composable (MonSig R0) 1 (Ar 1 [s]) (Ar 1 [s])).
  { split; [reflexivity | split; [simpl; lia | simpl; split; [reflexivity | apply c_refl]]]. }
  destruct P as (P1 & P2 & P3).
  destruct (S1 _ (I_comp (MonSig R0) (sigmaM R0) 1 _ _ _ _ P1 P2 P3 Hs Hs)) as (c' & Hc' & _).
  unfold paper_rhs in Hc'.
  destruct (Interp_comp_inv _ _ _ _ _ _ Hc') as (p & q & B1 & B2 & B3 & _ & Hp & Hq).
  destruct (Interp_id_inv _ _ _ _ Hp) as (p0 & -> & Hp0).
  destruct (Interp_id_inv _ _ _ _ Hq) as (q0 & -> & Hq0).
  destruct (Interp_id_inv _ _ _ _ Hq0) as (q1 & -> & Hq1).
  destruct (Interp_src_inv _ _ _ _ Hq1) as (q2 & -> & Hq2 & _).
  apply (I_gen_inv (MonSig R0) (sigmaM R0)) in Hp0.
  apply (I_gen_inv (MonSig R0) (sigmaM R0)) in Hq2. subst p0 q2.
  simpl in B3. destruct B3 as [_ C].
  exact (paper_example_nontrivial s C).
Qed.

(** ** 10. What a decision procedure for EQ would give *)

Corollary weak_decider_gives_word_problem :
  (forall e1 e2, {InEQ_weak e1 e2} + {~ InEQ_weak e1 e2}) ->
  forall gens R u v, over gens R -> good gens u -> good gens v ->
  {cong R u v} + {~ cong R u v}.
Proof.
  intros D gens R u v Hov Gu Gv.
  destruct (D (wp_term gens R u) (wp_term gens R v)) as [Y | N].
  - left. apply (word_problem_reduces gens R u v Hov Gu Gv). exact Y.
  - right. intro C. apply N. apply (word_problem_reduces gens R u v Hov Gu Gv). exact C.
Qed.

Corollary strong_decider_gives_triviality :
  (forall e1 e2, {InEQ_strong e1 e2} + {~ InEQ_strong e1 e2}) ->
  forall gens R, over gens R ->
  {forall a, In a gens -> cong R [a] []} + {~ forall a, In a gens -> cong R [a] []}.
Proof.
  intros D gens R Hov.
  destruct (D (enc gens R) (enc gens (triv gens))) as [Y | N].
  - left. apply (triviality_reduces gens R Hov). exact Y.
  - right. intro C. apply N. apply (triviality_reduces gens R Hov). exact C.
Qed.

End WordProblemF.

