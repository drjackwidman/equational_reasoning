(** * WordProblem.v
    Reductions from problems about finitely presented monoids to membership
    in the set EQ of valid equations (Section "Undecidability of Global
    Validity" of the paper).

    A presentation is a list of generators and a list of relations (pairs
    of words). [cong R] is the congruence it generates on words.

    Two readings of "the equation e1 = e2 is in EQ" are formalized:

      - [InEQ_weak]: in every model and under every interpretation, if
        both sides are defined then they are equal. This is the definition
        in the text of the paper.
      - [InEQ_strong]: in every model and under every interpretation, the
        two sides are defined together, and equal when defined. This is
        the definition in a commented-out block of the paper's source.

    Results:

      - [word_problem_reduces]: u and v are equal in the presented monoid
        iff an equation built from the presentation, u and v is in EQ
        under the weak reading.
      - [presentations_reduce], [triviality_reduces]: two presentations
        over the same generators present the same monoid iff the equation
        between their encodings is in EQ under the strong reading; the
        presentation is trivial iff its encoding equals that of the
        trivial presentation.
      - [presentation_equation_weak]: under the weak reading that last
        equation is in EQ for every pair of presentations, so it decides
        nothing.
      - [paper_equation_weak], [paper_equation_not_strong]: the same
        mismatch for the literal equation of the paper's proof, on the
        presentation with one generator s and the relation s = s.

    These are reductions. That the word problem and the triviality problem
    for monoids are undecidable is a cited theorem and is not formalized
    here. So what is proved is: a decision procedure for EQ would give
    one for the word problem ([weak_decider_gives_word_problem]) or for
    triviality ([strong_decider_gives_triviality]).

    The encoding is not the paper's term for term. A relation l = r is
    still encoded by the composite id l ∘_1 id r, which is defined exactly
    when l and r denote the same cell. Two things are added: a 0-cell
    generator for the base point, so that the empty word has a term
    (its identity), and for each generator a term that is defined exactly
    when the generator is a loop on the base point. *)

